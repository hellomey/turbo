#!/usr/bin/env node
// Generates docs/architecture/modules.md (table + dependency graph) from every module.json.
//   node tools/gen-module-docs.mjs          write
//   node tools/gen-module-docs.mjs --check  fail if stale (CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "packages/domain/src/modules");
const mods = readdirSync(dir)
  .filter((m) => existsSync(join(dir, m, "module.json")))
  .map((m) => JSON.parse(readFileSync(join(dir, m, "module.json"), "utf8")))
  .sort((a, b) => (a.buildWeek ?? 99) - (b.buildWeek ?? 99) || a.name.localeCompare(b.name));

const id = (n) => n.replace(/-/g, "_");
const md = [
  "# Backend modules",
  "",
  "> GENERATED by `tools/gen-module-docs.mjs` from `packages/domain/src/modules/*/module.json`. Do not edit.",
  "",
  "Arrows point from a module to the modules it may import (through their `index.ts`). Anything else fails `pnpm boundaries`.",
  "",
  "```mermaid",
  "graph LR",
  ...mods.flatMap((m) => (m.dependsOn.length ? m.dependsOn.map((d) => `  ${id(m.name)} --> ${id(d)}`) : [`  ${id(m.name)}`])),
  ...mods.filter((m) => m.founderApprovalRequired).map((m) => `  style ${id(m.name)} stroke-width:3px`),
  "```",
  "",
  "Thick border = founder approval on every change (money, personal data, game fairness, security).",
  "",
  "| Module | Week | Coverage | Founder approval | Owns | May depend on |",
  "|---|---|---|---|---|---|",
  ...mods.map(
    (m) =>
      `| [\`${m.name}\`](../../packages/domain/src/modules/${m.name}/MODULE.md) | ${m.buildWeek ?? "later"} | ${m.coverageTarget}% | ${m.founderApprovalRequired ? "yes" : "—"} | ${m.owns.join(", ")} | ${m.dependsOn.join(", ") || "—"} |`,
  ),
  "",
].join("\n");

const out = join(root, "docs/architecture/modules.md");
const current = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : null;
if (process.argv.includes("--check")) {
  if (current !== md) {
    console.error("docs/architecture/modules.md is stale. Run `pnpm docs:gen`.");
    process.exit(1);
  }
  console.log("module docs: up to date");
} else if (current !== md) {
  writeFileSync(out, md);
  console.log("wrote docs/architecture/modules.md");
}
