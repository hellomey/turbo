#!/usr/bin/env bash
# One-time VM provisioning (Ubuntu 24.04 LTS, Indian data centre: Oracle Always Free Ampere A1 (arm64) in
# Mumbai/Hyderabad, or Hetzner (amd64); BOLT-0023). Blueprint §20.3, §23.
# Run as root on a fresh box:  bash provision.sh <deploy-user> <ssh-port>
# Idempotent: safe to re-run. Also step 1 of the "new VPS" runbook (docs/runbooks/vps-rebuild.md).
set -euo pipefail

DEPLOY_USER="${1:?deploy user}"
SSH_PORT="${2:?non-default ssh port}"

apt-get update
apt-get -y upgrade
apt-get install -y ca-certificates curl gnupg ufw unattended-upgrades age sops git

# Docker Engine + Compose plugin
install -m 0755 -d /etc/apt/keyrings
curl -fsSL https://download.docker.com/linux/ubuntu/gpg | gpg --dearmor -o /etc/apt/keyrings/docker.gpg --yes
echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/ubuntu $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
  > /etc/apt/sources.list.d/docker.list
apt-get update
apt-get install -y docker-ce docker-ce-cli containerd.io docker-compose-plugin

# Deploy user, SSH keys only, non-default port
id "$DEPLOY_USER" >/dev/null 2>&1 || adduser --disabled-password --gecos "" "$DEPLOY_USER"
usermod -aG docker "$DEPLOY_USER"
sed -ri "s/^#?Port .*/Port ${SSH_PORT}/; s/^#?PasswordAuthentication .*/PasswordAuthentication no/; s/^#?PermitRootLogin .*/PermitRootLogin no/" /etc/ssh/sshd_config
systemctl restart ssh

# Firewall: ONLY 80/443 (+ SSH). Every 45xx port stays on 127.0.0.1 / the Docker network.
ufw default deny incoming
ufw default allow outgoing
ufw allow "${SSH_PORT}/tcp"
ufw allow 80/tcp
ufw allow 443/tcp
ufw allow 443/udp
ufw --force enable

# OPTIONAL (BOLT-0007 SEC-H1, blueprint §23): accept 80/443 ONLY from Cloudflare, so nobody can bypass the CDN/WAF
# and hit Caddy directly. Off by default; enable with:  CF_ONLY_ORIGIN=1 bash provision.sh <user> <ssh-port>
# (needs the DNS records proxied - orange cloud - first, or ACME HTTP challenges and direct users are cut off).
# NOTE: plain `ufw allow from <cf>` does NOT work for Caddy: Docker-published ports are DNATed before ufw's INPUT
# chain sees them. The rules go into Docker's DOCKER-USER chain instead, re-applied at boot by a systemd unit.
# SSH is untouched (still the ufw rule above), so the box stays reachable. Keep the ranges in sync with the
# trusted_proxies list in infra/caddy/Caddyfile (https://www.cloudflare.com/ips-v4, /ips-v6).
# Undo: systemctl disable --now heymey-cf-origin && iptables -D DOCKER-USER ... (or reboot after disabling).
cloudflare_only_origin() {
  local iface
  iface=$(ip route show default | awk '/default/ {print $5; exit}')
  cat > /usr/local/sbin/heymey-cf-origin <<EOF
#!/bin/sh
# Generated by infra/scripts/provision.sh: 80/443 on ${iface} only from Cloudflare (Docker DOCKER-USER chain).
set -eu
V4="173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18 108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17 162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22"
V6="2400:cb00::/32 2606:4700::/32 2803:f800::/32 2405:b500::/32 2405:8100::/32 2a06:98c0::/29 2c0f:f248::/32"
apply() { # \$1 = iptables|ip6tables, \$2 = ranges
  T=\$1
  \$T -n -L DOCKER-USER >/dev/null 2>&1 || \$T -N DOCKER-USER
  \$T -N HEYMEY-CF 2>/dev/null || \$T -F HEYMEY-CF
  for r in \$2; do \$T -A HEYMEY-CF -s "\$r" -j RETURN; done
  \$T -A HEYMEY-CF -j DROP
  for p in tcp udp; do
    \$T -C DOCKER-USER -i ${iface} -p \$p -m multiport --dports 80,443 -j HEYMEY-CF 2>/dev/null \\
      || \$T -I DOCKER-USER -i ${iface} -p \$p -m multiport --dports 80,443 -j HEYMEY-CF
  done
}
apply iptables "\$V4"
command -v ip6tables >/dev/null && apply ip6tables "\$V6" || true
EOF
  chmod 0755 /usr/local/sbin/heymey-cf-origin
  cat > /etc/systemd/system/heymey-cf-origin.service <<'EOF'
[Unit]
Description=HeyMey: 80/443 only from Cloudflare (DOCKER-USER)
After=docker.service
PartOf=docker.service

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/heymey-cf-origin
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target docker.service
EOF
  systemctl daemon-reload
  systemctl enable --now heymey-cf-origin.service
}

# Oracle Cloud images (BOLT-0023) ship their own iptables REJECT rules in /etc/iptables/rules.v4 that block 80/443
# even when ufw allows them. Open them in the host rules too (also open 80/443 in the OCI subnet security list).
if [ -f /etc/iptables/rules.v4 ] && grep -q "REJECT" /etc/iptables/rules.v4; then
  for p in 80 443; do
    iptables -C INPUT -p tcp --dport "$p" -j ACCEPT 2>/dev/null || iptables -I INPUT 5 -p tcp --dport "$p" -j ACCEPT
  done
  iptables -C INPUT -p udp --dport 443 -j ACCEPT 2>/dev/null || iptables -I INPUT 5 -p udp --dport 443 -j ACCEPT
  command -v netfilter-persistent >/dev/null && netfilter-persistent save
fi

# Small VMs: 4 GB swap so a build spike never OOM-kills Valkey (no-op if swap exists).
if ! swapon --show | grep -q .; then
  fallocate -l 4G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# CrowdSec (bouncer on the host firewall)
curl -s https://install.crowdsec.net | bash  # nosemgrep: bash.curl.security.curl-pipe-bash.curl-pipe-bash -- retired VPS path (CLAUDE.md section 3); moves to infra/legacy-docker in BOLT-0027
apt-get install -y crowdsec crowdsec-firewall-bouncer-iptables

# Automatic security updates
dpkg-reconfigure -f noninteractive unattended-upgrades

# Shared edge network for Caddy <-> production/staging stacks
docker network inspect heymey-edge >/dev/null 2>&1 || docker network create heymey-edge

# Optional Cloudflare-only origin (see cloudflare_only_origin above). Off unless CF_ONLY_ORIGIN=1.
if [ "${CF_ONLY_ORIGIN:-0}" = 1 ]; then
  cloudflare_only_origin
  echo "80/443 now accept Cloudflare only (SSH on ${SSH_PORT} unchanged)"
fi

mkdir -p /srv/heymey && chown "$DEPLOY_USER":"$DEPLOY_USER" /srv/heymey
echo "provisioned. Next: clone the repo into /srv/heymey, place the age key at /srv/heymey/.age/key.txt, run deploy.sh"
